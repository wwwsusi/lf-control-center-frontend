// Generates the CRM light mode from the dark stylesheets and writes it between the markers at the end of web/crm.css.
// Run after changing colours: node scripts/gen-crm-light.mjs   (tests/crm-light.test.mjs fails when the block is stale).
// Rules: dark surfaces become light, light text becomes dark, borders become soft; accent backgrounds (brand pink etc.) and
// anything that is already light stay as they are. The printed client card and the printed body report are never touched.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCES = ['web/home.css', 'web/crm.css', 'web/crm-control-center.css', 'web/crm-body.css', 'web/crm-packages.css'];
export const BEGIN = '/* light:begin (generated by scripts/gen-crm-light.mjs; do not edit by hand) */';
export const END = '/* light:end */';
const SCOPE = 'html[data-theme=light]';
const SKIP_SELECTOR = /\.lf-report|\.pc-|\.crm-print-card|\.brand\b|qr/i;

// Base tokens the stylesheets read through var(); hand-picked to match the Control Center light theme.
const TOKENS = `${SCOPE}{color-scheme:light;--navy:#f2f4f8;--text:#0f1d30;--muted:#526073;--pink:#d30b52}`;

const clamp = (v, a, b) => Math.min(b, Math.max(a, v));
export function parseColor(raw) {
  let m = raw.match(/^#([0-9a-f]{3,8})$/i);
  if (m) {
    let h = m[1];
    if (h.length === 3 || h.length === 4) h = [...h].map(c => c + c).join('');
    if (h.length !== 6 && h.length !== 8) return null;
    return {r: parseInt(h.slice(0, 2), 16), g: parseInt(h.slice(2, 4), 16), b: parseInt(h.slice(4, 6), 16), a: h.length === 8 ? parseInt(h.slice(6), 16) / 255 : 1};
  }
  m = raw.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/i);
  return m ? {r: +m[1], g: +m[2], b: +m[3], a: m[4] === undefined ? 1 : +m[4]} : null;
}
export function toHsl({r, g, b}) {
  const R = r / 255, G = g / 255, B = b / 255, max = Math.max(R, G, B), min = Math.min(R, G, B), l = (max + min) / 2, d = max - min;
  if (!d) return {h: 0, s: 0, l};
  const s = d / (1 - Math.abs(2 * l - 1));
  const h = 60 * (max === R ? ((G - B) / d + 6) % 6 : max === G ? (B - R) / d + 2 : (R - G) / d + 4);
  return {h, s, l};
}
export function fromHsl({h, s, l}, a = 1) {
  const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs((h / 60) % 2 - 1)), m = l - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  const hex = v => Math.round(clamp(v + m, 0, 1) * 255).toString(16).padStart(2, '0');
  return '#' + hex(r) + hex(g) + hex(b) + (a < 1 ? hex(a - m) : '');
}
const hex2 = v => Math.round(clamp(v, 0, 1) * 255).toString(16).padStart(2, '0');
const out = (hsl, a) => fromHsl(hsl) + (a < 1 ? hex2(a) : '');
const isAccent = c => c.s > 0.55 && c.l > 0.3 && c.l < 0.75;

// role: 'surface' | 'text' | 'line'. Returns the light-mode colour, or null to keep the original.
export function lightColor(raw, role, {onAccent = false} = {}) {
  const p = parseColor(raw);
  if (!p) return null;
  const c = toHsl(p);
  if (role === 'surface') {
    if (c.l >= 0.45) return null;
    const tinted = c.s > 0.28 && !(c.h > 195 && c.h < 235); // status colours keep their hue, navy surfaces turn neutral
    const l = tinted ? 0.93 : c.l <= 0.2 ? clamp(0.955 + (c.l - 0.09) * 0.45, 0.945, 1) : 0.91;
    return out({h: c.h, s: Math.min(c.s, tinted ? 0.65 : 0.32), l}, p.a);
  }
  if (role === 'line') {
    if (isAccent(c)) return null;
    return c.l < 0.55 ? out({h: c.h, s: Math.min(c.s, 0.25), l: c.l < 0.35 ? 0.84 : 0.72}, p.a) : out({h: c.h, s: Math.min(c.s, 0.4), l: 0.5}, p.a);
  }
  if (onAccent || c.l <= 0.45) return null; // text on a brand button stays; dark text is already fine
  if (c.s < 0.35 || c.l >= 0.9) return out({h: 215, s: 0.42, l: c.l >= 0.85 ? 0.13 : 0.35}, p.a);
  return out({h: c.h, s: Math.min(c.s, 0.85), l: c.h > 25 && c.h < 200 ? 0.26 : 0.38}, p.a);
}

const COLOR = /#[0-9a-f]{3,8}\b|rgba?\([^)]*\)/gi;
// Custom properties carry colours too (report cards, status tones): the role follows from the name. The brand pink is kept.
const roleOfToken = name => name === '--pink' ? null : /(bg|paper|surface|subtle|card|navy)/.test(name) ? 'surface' : /(line|border)/.test(name) ? 'line' : 'text';
const roleOf = prop => prop.startsWith('--') ? roleOfToken(prop) : /^(background|background-color|background-image)$/.test(prop) ? 'surface'
  : /^(color|fill|-webkit-text-fill-color|caret-color)$/.test(prop) ? 'text'
  : /^(border(-(top|right|bottom|left))?(-color)?|outline(-color)?|stroke)$/.test(prop) ? 'line' : null;

// Splits a stylesheet into {selector, body} rules; keeps one level of @media, drops print and other at-rules.
export function rules(css) {
  const list = [];
  const walk = (text, media) => {
    let i = 0;
    while (i < text.length) {
      const open = text.indexOf('{', i);
      if (open < 0) return;
      let depth = 1, j = open + 1;
      for (; j < text.length && depth; j++) depth += text[j] === '{' ? 1 : text[j] === '}' ? -1 : 0;
      const head = text.slice(i, open).replace(/^[\s;]+/, '').trim().replace(/^(@(charset|import)[^;]*;\s*)+/, ''), body = text.slice(open + 1, j - 1);
      if (head.startsWith('@media')) { if (!/print/.test(head)) walk(body, head); }
      else if (!head.startsWith('@') && head) list.push({selector: head, body, media});
      i = j;
    }
  };
  walk(css.replace(/\/\*[\s\S]*?\*\//g, ''), null);
  return list;
}

const splitTop = (s, sep) => { const parts = []; let depth = 0, cur = ''; for (const ch of s) { if (ch === '(') depth++; if (ch === ')') depth--; if (ch === sep && !depth) { parts.push(cur); cur = ''; } else cur += ch; } parts.push(cur); return parts.map(p => p.trim()).filter(Boolean); };
const scoped = sel => splitTop(sel, ',').map(s => /^(:root|html)\b/.test(s) ? s.replace(/^(:root|html)/, SCOPE) : SCOPE + ' ' + s).join(',');

export function lightRule({selector, body, media}) {
  const selectors = splitTop(selector, ',').filter(s => !SKIP_SELECTOR.test(s));
  if (!selectors.length) return null;
  const decls = splitTop(body, ';').map(d => { const k = d.indexOf(':'); return k < 0 ? null : [d.slice(0, k).trim().toLowerCase(), d.slice(k + 1).trim()]; }).filter(Boolean);
  const onAccent = decls.some(([p, v]) => roleOf(p) === 'surface' && (/var\(--pink/.test(v) || (v.match(COLOR) ?? []).some(x => { const c = parseColor(x); return c && c.a > 0.5 && isAccent(toHsl(c)); })));
  // Every colour declaration is repeated, remapped or not: the whole colour cascade moves up by the same specificity, so a brand
  // or status state written later (current tab, pressed button, accent border) still wins over the plain rule before it.
  const painted = [];
  for (const [prop, value] of decls) {
    const role = roleOf(prop);
    if (!role || (prop.startsWith('--') && !value.match(COLOR))) continue;
    painted.push(prop + ':' + value.replace(COLOR, raw => lightColor(raw, role, {onAccent: onAccent && !prop.startsWith('--')}) ?? raw));
  }
  if (!painted.length) return null;
  const rule = scoped(selectors.join(',')) + '{' + painted.join(';') + '}';
  return media ? media + '{' + rule + '}' : rule;
}

export const withoutBlock = css => { const a = css.indexOf(BEGIN); if (a < 0) return css; const b = css.indexOf(END, a); return css.slice(0, a) + css.slice(b + END.length); };
export function generate(read = f => fs.readFileSync(path.join(root, f), 'utf8')) {
  const lines = SOURCES.flatMap(f => rules(withoutBlock(read(f))).map(lightRule).filter(Boolean));
  return [BEGIN, TOKENS, ...lines, EXTRA, END].join('\n');
}

// Hand-written finishing touches the automatic mapping cannot know.
const EXTRA = `${SCOPE} .home-shell{background:none}
${SCOPE} .brand{box-shadow:0 0 0 1px #d9e0e9}
${SCOPE} #crm-content svg text{fill:#3a475a}`;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(root, 'web/crm.css');
  const base = withoutBlock(fs.readFileSync(file, 'utf8')).replace(/\n+$/, '');
  fs.writeFileSync(file, base + '\n\n' + generate() + '\n');
  console.log('light mode written: ' + generate().split('\n').length + ' lines');
}
